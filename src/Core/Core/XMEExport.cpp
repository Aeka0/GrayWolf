#include "stdafx.h"

#include "XMEExport.h"

#include "Strings.h"
#include "WraithModel.h"

#include <format>
#include <fstream>
#include <stdexcept>

void CodXME::ExportXME(const WraithModel& Model, const std::string& FileName)
{
    std::ofstream Writer(FileName);
    if (!Writer) throw std::runtime_error("cannot create " + FileName);
    Writer.rdbuf()->pubsetbuf(nullptr, 0x100000);   // MSVC: a 1 MB buffer, the file comes in small pieces
    Writer << "// Generated by Wraith - Game extraction tools\n"
        "// Please credit DTZxPorter for using it!\n"
        "MODEL\nVERSION 6\n" << '\n';
    Writer << std::format("NUMBONES {}\n", Model.BoneCount());
    uint32_t BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        Writer << std::format("BONE {} {} \"{}\"\n", BoneIndex, Bone.BoneParent, Bone.TagName.c_str());
        BoneIndex++;
    }
    Writer << '\n';
    BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        Matrix RotationMatrix = Matrix::CreateFromQuaternion(Bone.GlobalRotation);
        Writer << std::format(
            "BONE {}\n"
            "OFFSET {:f}, {:f}, {:f}\n"
            "SCALE {:f}, {:f}, {:f}\n"
            "X {:f}, {:f}, {:f}\n"
            "Y {:f}, {:f}, {:f}\n"
            "Z {:f}, {:f}, {:f}\n",
            BoneIndex,
            Bone.GlobalPosition.X, Bone.GlobalPosition.Y, Bone.GlobalPosition.Z,
            Bone.BoneScale.X, Bone.BoneScale.Y, Bone.BoneScale.Z,
            VectorMath::Clamp(RotationMatrix.Mat(0, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(0, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(0, 2), -1.0f, 1.0f),
            VectorMath::Clamp(RotationMatrix.Mat(1, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(1, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(1, 2), -1.0f, 1.0f),
            VectorMath::Clamp(RotationMatrix.Mat(2, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(2, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(2, 2), -1.0f, 1.0f)
            ) << '\n';
        BoneIndex++;
    }
    auto VertexCount = Model.VertexCount();
    auto FaceCount = Model.FaceCount();
    if (VertexCount > UINT16_MAX)
    {
        Writer << std::format("NUMVERTS32 {}\n", VertexCount);
    }
    else
    {
        Writer << std::format("NUMVERTS {}\n", VertexCount);
    }
    std::unordered_set<int32_t> MaterialIndicies;
    uint32_t VertexIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        MaterialIndicies.insert(Submesh.MaterialIndicies[0]);
        for (auto& Vertex : Submesh.Verticies)
        {
            if (VertexCount > UINT16_MAX)
            {
                Writer << std::format(
                    "VERT32 {}\n"
                    "OFFSET {:f}, {:f}, {:f}",
                    VertexIndex,
                    Vertex.Position.X, Vertex.Position.Y, Vertex.Position.Z
                    ) << '\n';
            }
            else
            {
                Writer << std::format(
                    "VERT {}\n"
                    "OFFSET {:f}, {:f}, {:f}",
                    VertexIndex,
                    Vertex.Position.X, Vertex.Position.Y, Vertex.Position.Z
                    ) << '\n';
            }
            if (Vertex.WeightCount() == 1)
            {
                Writer << std::format(
                    "BONES 1\n"
                    "BONE {} 1.000000\n",
                    Vertex.Weights[0].BoneIndex
                    ) << '\n';
            }
            else
            {
                Writer << std::format("BONES {}\n", (uint32_t)Vertex.WeightCount());
                for (auto& Weight : Vertex.Weights)
                {
                    Writer << std::format("BONE {} {:f}\n", Weight.BoneIndex, Weight.Weight);
                }
                Writer << '\n';
            }
            VertexIndex++;
        }
    }
    Writer << std::format("NUMFACES {}\n", FaceCount);
    uint32_t SubmeshIndex = 0;
    VertexIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        auto FindResult = MaterialIndicies.find(Submesh.MaterialIndicies[0]);
        uint32_t IndexOfMaterial = (FindResult != MaterialIndicies.end()) ? (uint32_t)std::distance(MaterialIndicies.begin(), FindResult) : 0;
        for (auto& Face : Submesh.Faces)
        {
            Writer << std::format("TRI {} {} 0 0\n", SubmeshIndex, IndexOfMaterial);
            Writer << std::format("{} {}\n", (VertexCount > UINT16_MAX) ? "VERT32" : "VERT", Face.Index3 + VertexIndex);
            Writer << std::format(
                "NORMAL {:f} {:f} {:f}\n"
                "COLOR {:f} {:f} {:f} {:f}\n"
                "UV 1 {:f} {:f}",
                Submesh.Verticies[Face.Index3].Normal.X, Submesh.Verticies[Face.Index3].Normal.Y, Submesh.Verticies[Face.Index3].Normal.Z,
                Submesh.Verticies[Face.Index3].Color[0] / 255.0f, Submesh.Verticies[Face.Index3].Color[1] / 255.0f, Submesh.Verticies[Face.Index3].Color[2] / 255.0f, Submesh.Verticies[Face.Index3].Color[3] / 255.0f,
                Submesh.Verticies[Face.Index3].UVLayers[0].U, Submesh.Verticies[Face.Index3].UVLayers[0].V
                ) << '\n';

            Writer << std::format("{} {}\n", (VertexCount > UINT16_MAX) ? "VERT32" : "VERT", Face.Index1 + VertexIndex);
            Writer << std::format(
                "NORMAL {:f} {:f} {:f}\n"
                "COLOR {:f} {:f} {:f} {:f}\n"
                "UV 1 {:f} {:f}",
                Submesh.Verticies[Face.Index1].Normal.X, Submesh.Verticies[Face.Index1].Normal.Y, Submesh.Verticies[Face.Index1].Normal.Z,
                Submesh.Verticies[Face.Index1].Color[0] / 255.0f, Submesh.Verticies[Face.Index1].Color[1] / 255.0f, Submesh.Verticies[Face.Index1].Color[2] / 255.0f, Submesh.Verticies[Face.Index1].Color[3] / 255.0f,
                Submesh.Verticies[Face.Index1].UVLayers[0].U, Submesh.Verticies[Face.Index1].UVLayers[0].V
                ) << '\n';

            Writer << std::format("{} {}\n", (VertexCount > UINT16_MAX) ? "VERT32" : "VERT", Face.Index2 + VertexIndex);
            Writer << std::format(
                "NORMAL {:f} {:f} {:f}\n"
                "COLOR {:f} {:f} {:f} {:f}\n"
                "UV 1 {:f} {:f}",
                Submesh.Verticies[Face.Index2].Normal.X, Submesh.Verticies[Face.Index2].Normal.Y, Submesh.Verticies[Face.Index2].Normal.Z,
                Submesh.Verticies[Face.Index2].Color[0] / 255.0f, Submesh.Verticies[Face.Index2].Color[1] / 255.0f, Submesh.Verticies[Face.Index2].Color[2] / 255.0f, Submesh.Verticies[Face.Index2].Color[3] / 255.0f,
                Submesh.Verticies[Face.Index2].UVLayers[0].U, Submesh.Verticies[Face.Index2].UVLayers[0].V
                ) << '\n';
        }
        VertexIndex += Submesh.VertexCount();
        SubmeshIndex++;
    }
    Writer << '\n';
    Writer << std::format("NUMOBJECTS {}\n", Model.SubmeshCount());
    SubmeshIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        Writer << std::format("OBJECT {} \"WraithMesh_{}\"\n", SubmeshIndex, SubmeshIndex);
        SubmeshIndex++;
    }
    Writer << '\n';
    Writer << std::format("NUMMATERIALS {}\n", (uint32_t)MaterialIndicies.size());
    uint32_t MaterialIndex = 0;
    for (auto& MaterialOffset : MaterialIndicies)
    {
        const WraithMaterial& Material = (MaterialOffset > -1) ? Model.Materials[MaterialOffset] : WraithMaterial::DefaultMaterial;
        Writer << std::format("MATERIAL {} \"{}\" \"Phong\" \"", MaterialIndex, Material.MaterialName.c_str());
        // Ensure we don't exceed 128 characters, APE (and probably Linker) limits it...
        if (!Strings::IsNullOrWhiteSpace(Material.DiffuseMapName) && Material.DiffuseMapName.size() < 112)
        {
            Writer << std::format("color:{}", Material.DiffuseMapName.c_str());
        }
        Writer << "\"\nCOLOR 0.000000 0.000000 0.000000 1.000000\nTRANSPARENCY 0.000000 0.000000 0.000000 1.000000\nAMBIENTCOLOR 1.000000 1.000000 1.000000 1.000000\nINCANDESCENCE 0.000000 0.000000 0.000000 1.000000\nCOEFFS 0.800000 0.000000\nGLOW 0.000000 0\nREFRACTIVE 6 1.000000\nSPECULARCOLOR 0.500000 0.500000 0.500000 1.000000\nREFLECTIVECOLOR 0.000000 0.000000 0.000000 1.000000\nREFLECTIVE 1 0.500000\nBLINN -1.000000 -1.000000\nPHONG 20.000000\n";
        MaterialIndex++;
    }
}