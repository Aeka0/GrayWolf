#include "stdafx.h"

#include "ValveSMDExport.h"

#include "WraithModel.h"

#include <format>
#include <fstream>
#include <ostream>
#include <stdexcept>

void ExportVertexInfo(std::ostream& Writer, const WraithVertex& Vertex)
{
    Vector3 NormNormal = Vertex.Normal.GetNormalized();

    Writer << std::format("0 {:f} {:f} {:f} {:f} {:f} {:f} {:f} {:f} {} ", Vertex.Position.X, Vertex.Position.Y, Vertex.Position.Z, NormNormal.X, NormNormal.Y, NormNormal.Z, Vertex.UVLayers[0].U, (1 - Vertex.UVLayers[0].V), (uint32_t)Vertex.Weights.size());
    for (auto& Weight : Vertex.Weights)
    {
        Writer << std::format("{} {:f} ", Weight.BoneIndex, Weight.Weight);
    }
    Writer << '\n';
}

void ValveSMD::ExportSMD(const WraithModel& Model, const std::string& FileName)
{
    std::ofstream Writer(FileName);
    if (!Writer) throw std::runtime_error("cannot create " + FileName);
    Writer.rdbuf()->pubsetbuf(nullptr, 0x100000);   // MSVC: a 1 MB buffer, the file comes in small pieces
    Writer << "version 1\n"
        "// Generated by Wraith - Game extraction tools\n"
        "// Please credit DTZxPorter for using it!\n"
        "nodes" << '\n';
    uint32_t BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        Writer << std::format("{} \"{}\" {}\n", BoneIndex, Bone.TagName.c_str(), Bone.BoneParent);
        BoneIndex++;
    }
    Writer << "end\n"
        "skeleton\ntime 0" << '\n';
    BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        Vector3 LocalRotation = Bone.LocalRotation.ToEulerAngles();
        Writer << std::format("{} {:f} {:f} {:f} {:f} {:f} {:f}\n", BoneIndex, Bone.LocalPosition.X, Bone.LocalPosition.Y, Bone.LocalPosition.Z, VectorMath::DegreesToRadians(LocalRotation.X), VectorMath::DegreesToRadians(LocalRotation.Y), VectorMath::DegreesToRadians(LocalRotation.Z));
        BoneIndex++;
    }
    Writer << "end\n";
    for (auto& Submesh : Model.Submeshes)
    {
        Writer << "triangles\n";
        const WraithMaterial& Material = (Submesh.MaterialIndicies[0] > -1) ? Model.Materials[Submesh.MaterialIndicies[0]] : WraithMaterial::DefaultMaterial;
        for (auto& Face : Submesh.Faces)
        {
            Writer << Material.MaterialName << '\n';
            // Output face vertex info for the faces (bone root, vertex, normal, uv) (Reverse clockwise order)
            ExportVertexInfo(Writer, Submesh.Verticies[Face.Index3]);
            ExportVertexInfo(Writer, Submesh.Verticies[Face.Index2]);
            ExportVertexInfo(Writer, Submesh.Verticies[Face.Index1]);
        }
        Writer << "end\n";
    }
}